const assert=require('node:assert/strict');
const {health}=require('../../earnings-gap/monitor.js');
const now=new Date('2026-10-14T10:00:00+08:00');
const monitor={version:'test',status:'PASS',source_status:'PASS',financial_asof:'2026-10-14',data_updated_at:'2026-10-14T08:30:00+08:00',counts:{announcements:0,processed:0,pending:0},attempt:{run_id:'1',started_at:'2026-10-14T08:25:00+08:00'}};
const live={version:'test',updated_at:monitor.data_updated_at};
const job={id:1,status:'completed',conclusion:'success',created_at:'2026-10-14T00:25:00Z'};
assert.equal(health(monitor,live,job,now).severity,0);
assert.equal(health({...monitor,financial_asof:'2026-10-13'},live,job,now).severity,3);
assert.equal(health({...monitor,status:'FAILED',error:'finance offline'},live,job,now).severity,3);
assert.equal(health({...monitor,status:'PARTIAL',issues:['巨潮已有公告，财务尚未覆盖']},live,job,now).severity,2);
assert.equal(health({...monitor,source_status:'FAILED'},live,job,now).severity,3);
assert.equal(health(monitor,{...live,updated_at:'older'},job,now).severity,2);
assert.equal(health(monitor,live,{...job,conclusion:'failure'},now).severity,3);
assert.equal(health(monitor,live,null,now).severity,2);
assert.equal(health(monitor,live,job,new Date('2026-10-14T15:46:00+08:00')).severity,3);
assert.equal(health(monitor,live,{...job,status:'in_progress',created_at:'2026-10-14T01:55:00Z'},now).severity,1);
assert.equal(health(monitor,live,{...job,status:'in_progress',created_at:'2026-10-14T00:55:00Z'},now).severity,3);
assert.equal(health(monitor,live,{...job,id:2,created_at:'2026-10-14T01:55:00Z'},now).severity,2);
assert.equal(health(monitor,{...live,version:'other'},job,now).severity,3);
assert.equal(health(null,live,job,now).severity,3);
assert.equal(health(monitor,live,job,now,['监控快照读取失败']).severity,2);
